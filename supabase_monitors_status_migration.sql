-- RLS engedélyezése anon / authenticated kliens számára (ha RLS be van kapcsolva)
DO $$
DECLARE
  tbl TEXT;
BEGIN
  FOREACH tbl IN ARRAY ARRAY['monitors', 'bodies', 'queens', 'treatments', 'syrup_pumps', 'history_logs', 'hive_meters', 'weather_logs', 'catalogs']
  LOOP
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = tbl) THEN
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', tbl);
      IF NOT EXISTS (
        SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = tbl AND policyname = 'allow_all_apiary_access'
      ) THEN
        EXECUTE format(
          'CREATE POLICY allow_all_apiary_access ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)',
          tbl
        );
      END IF;
    END IF;
  END LOOP;
END $$;
