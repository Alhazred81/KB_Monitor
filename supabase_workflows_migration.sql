-- 1. FOLYAMAT SABLONOK (Mestertervek, Kezelési sorozatok, Állapotgépek, Tartozék-időzítők)
CREATE TABLE IF NOT EXISTS public.workflow_templates (
  code TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  category TEXT NOT NULL DEFAULT 'kezeles', -- 'anyasitas' | 'anyaneveles' | 'atkairtas' | 'tartozek_idozito' | 'egyeb'
  mode TEXT NOT NULL DEFAULT 'schedule_plan', -- 'sequential' | 'schedule_plan' | 'timer_rule'
  description TEXT DEFAULT '',
  is_active BOOLEAN DEFAULT true,
  sort_order INTEGER DEFAULT 0,
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 2. FOLYAMAT LÉPÉSEK ÉS IDŐZÍTÉSEK (Itt írhatod át szabadon az órákat / napokat / szövegeket!)
CREATE TABLE IF NOT EXISTS public.workflow_steps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workflow_code TEXT NOT NULL REFERENCES public.workflow_templates(code) ON DELETE CASCADE,
  step_order INTEGER NOT NULL,
  step_key TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT DEFAULT '',
  button_label TEXT DEFAULT '',
  -- delay_hours jelentése:
  -- • 'sequential' módban: az előző lépéstől számított várakozás órában (pl. 72 = 3 nap, 336 = 14 nap)
  -- • 'schedule_plan' módban: a terv indulásától (0. naptól) számított eltolás órában (pl. 144 = +6. nap)
  -- • 'timer_rule' módban: a visszaszámláló hossza órában (pl. 24 = 24 órás szöktetés, 72 = 3 napos aljdeszka)
  delay_hours INTEGER NOT NULL DEFAULT 0,
  preferred_hour INTEGER, -- pl. 9 vagy 10 (délelőtti munka); NULL = órapontos visszaszámlálás
  auto_complete_on_start BOOLEAN DEFAULT false,
  lock_hours INTEGER DEFAULT 0, -- pl. 336 = 14 napos "Ne nyúlj hozzá!" lakat
  acoustic_interval_min INTEGER, -- pl. 15 = sűrített akusztikai figyelés lakat alatt
  status_effect TEXT, -- pl. 'red', 'green', 'orange' (opcionális státuszváltás a lépésbe lépéskor)
  urgency_override TEXT, -- pl. 'flashing_red', 'flashing_orange'
  updated_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE (workflow_code, step_order)
);

CREATE INDEX IF NOT EXISTS idx_workflow_steps_code_order
  ON public.workflow_steps(workflow_code, step_order ASC);

-- 3. KAPTÁRAK AKTÍV FOLYAMAT-ÁLLAPOTA (Egymást követő lépések egyértelmű követése duplikáció nélkül)
CREATE TABLE IF NOT EXISTS public.hive_workflows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  monitor_mac TEXT NOT NULL,
  workflow_code TEXT NOT NULL,
  current_step_order INTEGER NOT NULL DEFAULT 1,
  step_key TEXT NOT NULL,
  started_at TIMESTAMPTZ DEFAULT now(),
  step_started_at TIMESTAMPTZ DEFAULT now(),
  due_at TIMESTAMPTZ,
  is_completed BOOLEAN DEFAULT false,
  metadata JSONB DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE (monitor_mac, workflow_code)
);

CREATE INDEX IF NOT EXISTS idx_hive_workflows_mac
  ON public.hive_workflows(monitor_mac);

